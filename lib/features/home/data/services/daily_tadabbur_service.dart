  /// Returns the reflection of the day deterministically based on date.
  DailyTadabburItem getTodayTadabbur([DateTime? date]) {
    final d = date ?? DateTime.now();
    final dayOfYear = d.difference(DateTime(d.year, 1, 1)).inDays;
    final index = dayOfYear % items.length;
    return items[index];
  }

  /// Returns an item by its ID (1..30).
  DailyTadabburItem? getById(int id) {
    return items.firstWhere(
      (item) => item.id == id,
      orElse: () => items.first,
    );
  }
