  List<LandmarkItem> getByCity(String city) {
    if (city == 'الكل') return landmarks;
    return landmarks.where((l) => l.city == city).toList();
  }

  List<LandmarkItem> search(String query, {String? city}) {
    final q = query.trim().toLowerCase();
    return landmarks.where((l) {
      final matchesCity = (city == null || city == 'الكل' || l.city == city);
      final matchesQuery = q.isEmpty ||
          l.name.toLowerCase().contains(q) ||
          l.summary.toLowerCase().contains(q) ||
          l.virtues.toLowerCase().contains(q) ||
          l.category.toLowerCase().contains(q);
      return matchesCity && matchesQuery;
    }).toList();
  }
