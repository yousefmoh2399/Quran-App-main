  /// Saves the active wiping timer to local storage.
  Future<void> saveTimerState(WipingTimerState state) async {
    try {
      final prefs = await SharedPreferences.getInstance();
      await prefs.setString(_timerPrefsKey, jsonEncode(state.toMap()));
    } catch (_) {}
  }

  /// Loads the active wiping timer from local storage.
  Future<WipingTimerState?> getTimerState() async {
    try {
      final prefs = await SharedPreferences.getInstance();
      final raw = prefs.getString(_timerPrefsKey);
      if (raw == null || raw.isEmpty) return null;
      final map = jsonDecode(raw) as Map<String, dynamic>;
      return WipingTimerState.fromMap(map);
    } catch (_) {
      return null;
    }
  }

  /// Clears the wiping timer from local storage.
  Future<void> clearTimerState() async {
    try {
      final prefs = await SharedPreferences.getInstance();
      await prefs.remove(_timerPrefsKey);
    } catch (_) {}
  }

